import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const read = async p => JSON.parse(await readFile(new URL(p, root), 'utf8'));
const keyPattern = /^[a-z][a-z0-9-]*$/;
const legacy = {paper:'color-background',surface:'color-surface',ink:'color-text',muted:'color-text-muted',blue:'color-action','on-accent':'color-on-action',line:'color-border',tint:'color-tint',error:'color-error',positive:'color-positive',negative:'color-negative',pos_1:'color-pos-1',pos_2:'color-pos-2',pos_3:'color-pos-3',neg_1:'color-neg-1',neg_2:'color-neg-2',neg_3:'color-neg-3',neutral:'color-neutral',neu_1:'color-neutral',neu_2:'color-neutral',neu_3:'color-neutral',neu_4:'color-neutral',stage:'color-stage'};
const paletteRoles = ['color-background','color-surface','color-text','color-text-muted','color-action','color-on-action'];

export function compileTokens(primitives, semantic, registry) {
  const literal = (key, token) => {
    if (!keyPattern.test(key) || !token || typeof token !== 'object') throw Error(`Invalid token: ${key}`);
    const {type,value} = token;
    const valid = type === 'color' ? /^#[\da-f]{6}$/i.test(value)
      : type === 'dimension' ? /^(?:0|\d+(?:\.\d+)?)(?:px|rem)$/.test(value)
      : type === 'number' ? typeof value === 'number' && Number.isFinite(value)
      : type === 'fontFamily' ? typeof value === 'string' && /^[\w\s",-]+$/.test(value) : false;
    if (!valid) throw Error(`Invalid ${type} value: ${key}`);
    return String(value);
  };
  Object.entries(primitives).forEach(([k,v]) => literal(k,v));
  const resolve = (key, mapping, trail = []) => {
    if (!keyPattern.test(key)) throw Error(`Invalid reference: ${key}`);
    if (trail.includes(key)) throw Error(`Circular reference: ${[...trail,key].join(' -> ')}`);
    // A semantic name may intentionally expose its same-named primitive.
    const value = mapping[key];
    if (value === undefined || value === `{${key}}`) {
      if (!Object.hasOwn(primitives,key)) throw Error(`Missing token: ${key}`);
      return literal(key,primitives[key]);
    }
    const match = typeof value === 'string' && /^\{([a-z][a-z0-9-]*)\}$/.exec(value);
    if (!match) throw Error(`Expected reference: ${key}`);
    return resolve(match[1],mapping,[...trail,key]);
  };
  const declarations = mapping => Object.keys(mapping).map(k => `--${k}:${resolve(k,mapping)};`).join('');
  let css = '/* Generated by tools/build-tokens.mjs. Edit design/tokens/*.json. */\n:root{' + declarations(semantic) + '}\n';
  const ids = new Set();
  if (!Array.isArray(registry.themes) || !registry.themes.length) throw Error('Missing themes');
  const themes = registry.themes.map(t => {
    if (!keyPattern.test(t.id) || ids.has(t.id) || !t.name || !t.description) throw Error(`Invalid/duplicate theme: ${t.id}`);
    ids.add(t.id);
    const result = {id:t.id,name:t.name,description:t.description};
    for (const mode of ['light','dark']) {
      if (!t.modes?.[mode]) throw Error(`Missing mode: ${t.id}/${mode}`);
      const mapping = {...semantic,...t.modes[mode]};
      mapping["color-stage"] ??= "{color-tint}";
      for (const role of Object.values(legacy)) {
        if (!/^#[\da-f]{6}$/i.test(resolve(role,mapping))) throw Error(`Invalid theme color: ${role}`);
      }
      result[mode] = paletteRoles.map(role => resolve(role,mapping));
      css += `:root[data-appearance="${t.id}"][data-theme="${mode}"],.theme-preview[data-appearance="${t.id}"][data-theme="${mode}"]{${declarations({...t.modes[mode],"color-stage":mapping["color-stage"]})}${Object.entries(legacy).map(([k,v])=>`--${k}:var(--${v});`).join('')}}\n`;
    }
    return result;
  });
  if (!ids.has('lemon')) throw Error('Missing default theme: lemon');
  const script = '/* Generated. Edit design/tokens/*.json. */\nwindow.CardexDesignThemes = ' + JSON.stringify(themes).replace(/</g,'\\u003c') + ';\n';
  return {css,script};
}

export async function buildTokens({check = false} = {}) {
  const {css,script} = compileTokens(...await Promise.all(['primitives','semantic','themes'].map(n=>read(`design/tokens/${n}.json`))));
  for (const [p,content] of [['styles/generated/tokens.css',css],['scripts/generated/theme-tokens.js',script]]) {
    if (check) {
      if (await readFile(new URL(p,root),'utf8') !== content) throw Error(`Stale generated file: ${p}`);
    } else {
      await mkdir(new URL('./',new URL(p,root)),{recursive:true});
      await writeFile(new URL(p,root),content);
    }
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await buildTokens({check:process.argv.includes('--check')});
  console.log('Design tokens: OK');
}
